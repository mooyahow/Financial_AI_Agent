
from dataclasses import dataclass
from typing import Optional
import os

@dataclass
class Settings:
    """
    프로젝트 전역 설정을 환경 변수 기반으로 관리.

    """

    api_key: str
    db_path: str
    llm_api_key: str
    llm_base_url: Optional[str]
    llm_model: str
    redis_url: Optional[str]
    api_key_header: str = "Authorization"


def load_settings() -> Settings:
    """
    환경 변수로부터 런타임 설정을 로드

    필수:
    - API_KEY
    - LLM_API_KEY

    선택:
    - LLM_BASE_URL: LLM 엔드포인트의 Base URL
    - LLM_MODEL: 사용할 LLM 모델 이름 (기본값: general-llm)
    - DB_PATH: DuckDB PATH (기본값: data/all_stocks.duckdb)
    - REDIS_URL: Redis 연결 문자열 (기본값: None)
    - API_KEY_HEADER: API 키를 전달하는 헤더 이름 (기본값: Authorization)
    """

    api_key = os.getenv("API_KEY", "")
    llm_api_key = os.getenv("LLM_API_KEY", "")

    if not llm_api_key:
        raise ValueError("LLM_API_KEY 환경 변수가 설정되어 있지 않습니다.")

    return Settings(
        api_key=api_key,
        db_path=os.getenv("DB_PATH", "data/all_stocks.duckdb"),
        llm_api_key=llm_api_key,
        llm_base_url=os.getenv("LLM_BASE_URL"),
        llm_model=os.getenv("LLM_MODEL", "general-llm"),
        redis_url=os.getenv("REDIS_URL"),
        api_key_header=os.getenv("API_KEY_HEADER", "Authorization"),
    )


